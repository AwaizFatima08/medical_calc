// Writes docs/calculator-register.md from the registry and golden files.
// Run: dart run tool/make_register.dart
import 'dart:convert';
import 'dart:io';

import 'package:medicalcalc/calc/catalog.dart';
import 'package:medicalcalc/calc/registry.dart';

void main() {
  final out = StringBuffer()
    ..writeln('# Calculator register')
    ..writeln()
    ..writeln('Generated by `dart run tool/make_register.dart` on ${DateTime.now().toIso8601String().substring(0, 10)}. '
        'Every tool shows "Review pending" until Homi signs it off here and `reviewedOn` is set in its definition (design §9).')
    ..writeln()
    ..writeln('How to review a tool: open it in the app, check the inputs, bands and wording against the sources, '
        'try the golden cases in `test/golden/<id>.json`, then fill in the last two columns.')
    ..writeln();
  for (final mode in ToolMode.values) {
    out
      ..writeln('## ${mode == ToolMode.doctor ? 'Doctor mode' : 'Public mode'}')
      ..writeln()
      ..writeln('| Tool | Version / source | Golden cases | Open points | Reviewed by | Date |')
      ..writeln('|---|---|---|---|---|---|');
    for (final t in toolsFor(mode)) {
      final def = kCalculators[t.id];
      final golden = File('test/golden/${t.id}.json');
      final cases = golden.existsSync()
          ? ((jsonDecode(golden.readAsStringSync()) as Map)['cases'] as List).length
          : 0;
      final version = def?.version ??
          (kCustomScreens.contains(t.id) ? 'Unit factors (see units.dart)' : '**Not built yet**');
      final open = _open[t.id] ?? '';
      out.writeln('| ${t.name} (`${t.id}`) | $version | $cases | $open | | |');
    }
    out.writeln();
  }
  File('docs/calculator-register.md').writeAsStringSync(out.toString());
  stdout.writeln('wrote docs/calculator-register.md');
}

