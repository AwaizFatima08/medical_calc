  'p_bmi': 'Same cut-off question as body_size',
  'p_bp': 'Pakistan Hypertension League 2023 categories not yet compared with AHA/ACC 2025',
  'p_diabetes_risk': 'IDRS not validated in Pakistan; wording of activity options',
  'corrected_sodium': 'Headline uses Hillier 2.4 (Katz 1.6 shown too)',
  'apri_fib4': 'AST upper limit entered by user; cut-off pairs by disease',
  'dengue': 'WHO 2025 arboviral guideline not yet checked; NIH Pakistan list differs from WHO',
  'ramadan_risk': 'IDF-DAR 2026: totals like 3.25 put in the higher band; frailty text (2.5) vs figure (4)',
  'p_ramadan': 'Plain-language checklist, not a validated score',
  'gcs': 'Email GCS team about use in an ad-funded app',
  'qtc': 'Female limit 460 ms (AHA 2009); no short-QT band',
  'p_heat': 'Heat index bands are US NWS; no Pakistan-specific thresholds',
  'who_growth': 'BMI-for-age not included (no expanded WHO table found)',
